
# EJERCICIO 4: Crear una clase `Producto` con atributos `nombre` y `precio`.
# Crear una clase `Tienda` que tenga un atributo `inventario` (una lista de productos).
# La clase `Tienda` debe tener un método `agregar_producto` y otro método `mostrar_inventario`.

# - Define la clase `Producto` con un constructor que acepte `nombre` y `precio`.
# - Define la clase `Tienda` con un constructor que inicialice `inventario` como una lista vacía.
# - Implementa el método `agregar_producto` que añada instancias de `Producto` al `inventario`.
# - Implementa el método `mostrar_inventario` que recorra el inventario y muestre el nombre y precio de cada producto.
