# Crear una clase `Empresa` que tenga un atributo `empleados` (lista de empleados).
# Implementar métodos en `Empresa` para `contratar_empleado`, `listar_empleados`, y `calcular_salario_total`.

# - Define la clase `Empleado` con un constructor que acepte `nombre`, `puesto` y `salario`.
# - Define la clase `Empresa` con un constructor que inicialice `empleados` como una lista vacía.
# - Implementa el método `contratar_empleado` que añada un objeto `Empleado` a la lista `empleados`.
# - Implementa `listar_empleados` que recorra la lista de empleados y muestre sus nombres y puestos.
# - Implementa `calcular_salario_total` que sume y devuelva el salario total de todos los empleados.
